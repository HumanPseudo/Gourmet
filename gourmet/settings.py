def log_format() -> str:
    """
    Dump all available values into the JSON log output
    """
    keys = (
        "asctime",
        "created",
        "levelname",
        "levelno",
        "filename",
        "funcName",
        "lineno",
        "module",
        "message",
        "name",
        "pathname",
        "process",
        "processName",
    )
    return " ".join([f"%({i:s})" for i in keys])


